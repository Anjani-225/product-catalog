CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(64) NOT NULL,
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(4000),
    category    VARCHAR(120) NOT NULL,
    price       NUMERIC(19, 2) NOT NULL,
    currency    VARCHAR(3) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    version     BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT uk_products_sku UNIQUE (sku),
    CONSTRAINT ck_products_price_non_negative CHECK (price >= 0),
    CONSTRAINT ck_products_currency_usd CHECK (currency = 'USD')
);

-- Supports category-only filtering with the default deterministic id ordering.
CREATE INDEX idx_products_category_id ON products (category, id);

-- Supports price ranges and price-first pagination; id is the unique tie-breaker.
CREATE INDEX idx_products_price_id ON products (price, id);

-- Supports the common combined category + price range query and price ordering.
CREATE INDEX idx_products_category_price_id ON products (category, price, id);
